import { existsSync, lstatSync, readdirSync, readFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve } from "node:path";
import type { OutputFile } from "../utils/output";
import { sha256 } from "./acquisition";

/** Constrain output paths and reject symlinks before reading or changing outputs. */
export function outputPath(cwd: string, path: string): string {
  const absolute = resolve(cwd, path);
  const local = relative(cwd, absolute);
  if (
    !local ||
    local === ".." ||
    local.startsWith(`..${sep}`) ||
    isAbsolute(local) ||
    local.split(sep).includes(".git")
  ) {
    throw new Error(`Unsafe output ownership path: ${path}`);
  }
  let current = absolute;
  while (current !== cwd) {
    if (existsSync(current) && lstatSync(current).isSymbolicLink()) {
      throw new Error(`Symlink in output ownership path: ${path}`);
    }
    current = dirname(current);
  }
  return absolute;
}

const sep = process.platform === "win32" ? "\\" : "/";

// Older Typeforge versions already identify generated files with this exact banner.
const legacyMarker =
  /^\/\/ Auto-generated from OpenAPI spec\n(?:\/\/ Path: [^\n]+\n)?\/\/ DO NOT EDIT - This file is automatically generated\n/m;

function matchesLegacyOwnership(existing: string, expected: string): boolean {
  const banner = existing.match(legacyMarker)?.[0];
  return banner !== undefined && banner === expected.match(legacyMarker)?.[0];
}

const marker = /^\/\/ @typeforge-owned (\S+) sha256:([a-f0-9]{64})\n/;

export function stripOwnership(content: string): string {
  return content.replace(marker, "");
}

/** Ownership lives in each generated file, never in a directory inventory. */
export function planOwnership(
  cwd: string,
  sourceDir: string,
  roots: Array<string>,
  files: Array<OutputFile>,
  merge: boolean,
  routesFile: string
): {
  files: Array<OutputFile>;
  obsolete: Array<string>;
  conflicts: Array<string>;
} {
  const owner = encodeURIComponent(
    relative(cwd, sourceDir).split(sep).join("/")
  );
  const expected = new Set(files.map((file) => outputPath(cwd, file.path)));
  const conflicts: Array<string> = [];
  const obsolete: Array<string> = [];
  const visited = new Set<string>();
  const scan = (path: string): void => {
    outputPath(cwd, path);
    if (visited.has(path) || !existsSync(path)) {
      return;
    }
    visited.add(path);
    if (lstatSync(path).isDirectory()) {
      for (const entry of readdirSync(path)) {
        scan(join(path, entry));
      }
      return;
    }
    if (!lstatSync(path).isFile()) {
      throw new Error(`Output is not a regular file: ${path}`);
    }
    const content = readFileSync(path, "utf8");
    const match = content.match(marker);
    if (match?.[1] !== owner || expected.has(path)) {
      return;
    }
    if (!merge) {
      obsolete.push(path);
    }
    if (sha256(stripOwnership(content)) !== match[2]) {
      conflicts.push(path);
    }
  };
  for (const root of roots) {
    scan(root);
  }
  const marked = files.map((file) => {
    if (existsSync(file.path)) {
      const existing = readFileSync(file.path, "utf8");
      const match = existing.match(marker);
      if (
        match
          ? match[1] !== owner
          : existing !== file.content &&
            !matchesLegacyOwnership(existing, file.content) &&
            !(merge && file.path === routesFile)
      ) {
        conflicts.push(file.path);
      }
    }
    return {
      path: file.path,
      content: `// @typeforge-owned ${owner} sha256:${sha256(file.content)}\n${file.content}`,
    };
  });
  return { files: marked, obsolete, conflicts };
}
